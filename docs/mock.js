  // FNV-1a 确定性字符串哈希 → uint32
  function hash32(str) {
    var h = 0x811c9dc5;
    for (var i = 0; i < str.length; i++) {
      h ^= str.charCodeAt(i);
      h = (h + ((h << 1) + (h << 4) + (h << 7) + (h << 8) + (h << 24))) >>> 0;
    }
    return h >>> 0;
  }

  // mulberry32 确定性伪随机
  function rng(seed) {
    var a = seed >>> 0;
    return function () {
      a |= 0; a = (a + 0x6d2b79f5) | 0;
      var t = Math.imul(a ^ (a >>> 15), 1 | a);
      t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
      return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
  }

  function pick(arr, r) { return arr[Math.floor(r() * arr.length)]; }
  function shuffle(arr, r) {
    var a = arr.slice();
    for (var i = a.length - 1; i > 0; i--) {
      var j = Math.floor(r() * (i + 1));
      var t = a[i]; a[i] = a[j]; a[j] = t;
    }
    return a;
  }

  function resolveCity(dest) {
    if (CANDIDATES[dest]) return { key: dest, city: CANDIDATES[dest], generic: false };
    for (var k in CANDIDATES) {
      if (dest.indexOf(k) >= 0 || k.indexOf(dest) >= 0) return { key: k, city: CANDIDATES[k], generic: false };
    }
    return { key: dest, city: genericCity(dest), generic: true };
  }

  function genericCity(dest) {
    var c = hash32(dest);
    var centerLat = 22 + (c % 1000) / 1000 * 20;
    var centerLng = 100 + (Math.floor(c / 1024) % 1000) / 1000 * 22;
    function jitter(salt) {
      var r = ((c + salt * 2654435761) >>> 0) % 10000 / 10000 - 0.5;
      return r * 0.12;
    }
    return {
      center: [centerLat, centerLng],
      spots: GENERIC_SPOTS.map(function (s, i) { return [s[0], centerLat + jitter(i + 1), centerLng + jitter(i + 101), s[1], s[2], s[3]]; }),
      foods: GENERIC_FOODS.map(function (f, i) { return [f[0], centerLat + jitter(i + 201), centerLng + jitter(i + 301), f[1], f[2]]; }),
      hotels: GENERIC_HOTELS.map(function (h, i) { return [h[0], centerLat + jitter(i + 401), centerLng + jitter(i + 501), h[1], h[2]]; }),
      _generic: true
    };
  }

