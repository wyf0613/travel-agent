def _resolve_city(dest: str):
    """返回 (city_key, city_dict, is_generic)。"""
    if dest in CANDIDATES:
        return dest, CANDIDATES[dest], False
    # 模糊匹配：如「北京市」→ 北京，「成都东站」→ 成都
    for k in CANDIDATES:
        if k in dest or dest in k:
            return k, CANDIDATES[k], False
    return dest, _generic_city(dest), True


def _generic_city(dest: str) -> dict:
    """为未内置的城市生成一份示意数据：坐标落在中国境内、合理分散。

    用城市名 crc32 做确定性随机，保证同一城市每次结果一致。
    """
    crc = zlib.crc32(dest.encode("utf-8")) & 0xFFFFFFFF
    # 中心落在中国境内大致范围：lat 22~42, lng 100~122
    center_lat = 22.0 + (crc % 1000) / 1000 * 20.0
    center_lng = 100.0 + ((crc >> 10) % 1000) / 1000 * 22.0

    def jitter(salt: int, span: float = 0.12) -> float:
        r = ((crc + salt * 2654435761) % 10000) / 10000 - 0.5  # -0.5 ~ 0.5
        return r * span

    spots = [
        (name, center_lat + jitter(i + 1), center_lng + jitter(i + 101), price, dur, cat)
        for i, (name, price, dur, cat) in enumerate(_GENERIC_SPOTS)
    ]
    foods = [
        (fname, center_lat + jitter(i + 201), center_lng + jitter(i + 301), cu, fp)
        for i, (fname, cu, fp) in enumerate(_GENERIC_FOODS)
    ]
    hotels = [
        (hname, center_lat + jitter(i + 401), center_lng + jitter(i + 501), hp, hstar)
        for i, (hname, hp, hstar) in enumerate(_GENERIC_HOTELS)
    ]
    return {"center": (center_lat, center_lng), "spots": spots, "foods": foods, "hotels": hotels, "_generic": True}


def _mock_weather(city_key: str, date_str: str, source: str = "mock") -> Weather:
    """按 城市+日期 确定性生成示意天气（同一输入稳定输出）。"""
    rng = random.Random(zlib.crc32((city_key + date_str).encode("utf-8")) & 0xFFFFFFFF)
    options = [
        ("晴", 18, 27),
        ("多云", 17, 25),
        ("阴", 16, 23),
        ("小雨", 15, 21),
        ("雷阵雨", 18, 24),
        ("晴间多云", 19, 26),
    ]
    cond, tmin, tmax = rng.choice(options)
    return Weather(
        date=date_str,
        condition=cond,
        temp_min=tmin,
        temp_max=tmax,
        desc=f"{cond} {tmin}~{tmax}℃",
        source=source,
    )


