    city_key, city, is_generic = _resolve_city(destination)
    days = max(1, int(days))
    # 出发日期：解析失败或缺失则默认今天
    try:
        start = datetime.strptime(start_date, "%Y-%m-%d").date() if start_date else date.today()
    except ValueError:
        start = date.today()
    # 确定性随机：同一输入 -> 同一结果
    seed = hash((destination, days, tuple(preferences))) & 0xFFFFFFFF
    rng = random.Random(seed)

    # 1) 选景点
    spots = city["spots"]
    n_spots = min(len(spots), max(days, 3))
    chosen = rng.sample(spots, n_spots)
    attractions: list[Attraction] = []
    for i, (name, lat, lng, price, dur, cat) in enumerate(chosen):
        attractions.append(
            Attraction(
                id=f"a{i + 1}",
                name=name,
                location=Location(name=name, lat=lat, lng=lng),
                description=f"{name}是{destination}的一处{cat}。",
                ticket_price=price,
                visit_duration_hours=dur,
                category=cat,
            )
        )

    # 2) 餐饮（每天午+晚）
    meals: list[Meal] = []
    for d in range(days):
        for mtype, f in [
            ("lunch", city["foods"][d % len(city["foods"])]),
            ("dinner", city["foods"][(d + 1) % len(city["foods"])]),
        ]:
            fname, flat, flng, cu, fp = f
            meals.append(
                Meal(
                    id=f"m{len(meals) + 1}",
                    name=fname,
                    location=Location(name=fname, lat=flat, lng=flng),
                    cuisine=cu,
                    price_per_person=fp,
                    meal_type=mtype,
                )
            )

    # 3) 酒店（全程一家）
    hname, hlat, hlng, hp, hstar = rng.choice(city["hotels"])
    hotel = Hotel(
        id="h1",
        name=hname,
        location=Location(name=hname, lat=hlat, lng=hlng),
        price_per_night=hp,
        star=hstar,
    )

    # 4) 预算
    attr_cost = sum(a.ticket_price for a in attractions)
    hotel_cost = hp * max(days - 1, 1)
    meals_cost = sum(m.price_per_person for m in meals)
    transport = 50.0 * days
    total = attr_cost + hotel_cost + meals_cost + transport
    budget = Budget(
        total=round(total, 2),
        attractions=round(attr_cost, 2),
        hotel=round(hotel_cost, 2),
        meals=round(meals_cost, 2),
        transport=round(transport, 2),
    )

    # 5) 每日计划
    per_day = max(1, n_spots // days)
    days_plan: list[DayPlan] = []
    idx = 0
    for d in range(1, days + 1):
        day_attr = attractions[idx : idx + per_day]
        idx += per_day
        if d == days and idx < len(attractions):  # 余量补到最后一天
            day_attr += attractions[idx:]
        day_attr_ids = [a.id for a in day_attr]
        day_date = (start + timedelta(days=d - 1)).strftime("%Y-%m-%d")
        day_meal_ids = [f"m{2 * (d - 1) + 1}", f"m{2 * (d - 1) + 2}"]
        summary = f"第{d}天：游览「{ '、'.join(a.name for a in day_attr) }」"
        days_plan.append(
            DayPlan(
                day=d,
                date=day_date,
                weather=_mock_weather(city_key, day_date),
                attraction_ids=day_attr_ids,
                meal_ids=day_meal_ids,
                summary=summary,
            )
        )

    overview = (
        f"为您规划了{destination}{days}天行程，涵盖 {len(attractions)} 个景点、"
        f"{len(meals)} 餐与 1 家酒店，预算约 ¥{budget.total}。"
    )
    if is_generic:
        overview += (
            f"（注：{destination} 暂无内置示例数据，以下为示意路线；"
            "接入真实高德 API 后将展示该城市的真实景点、经纬度与价格。）"
        )
    return TripPlan(
        destination=destination,
        days=days,
        preferences=preferences,
        attractions=attractions,
        meals=meals,
        hotel=hotel,
        budget=budget,
        days_plan=days_plan,
        overview=overview,
    )
